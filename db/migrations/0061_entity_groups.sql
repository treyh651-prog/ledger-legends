insert into sched.run_policies (run_type, tier, reason, writes_ledger) values
  ('CFG-CREATE-ENTITY-GROUP', 'manual',
   'a firm declares which clients belong to the same group once, by hand, and a clock has no group of its own to discover', false),
  ('CFG-EDIT-ENTITY-GROUP', 'manual',
   'renaming or archiving a group is a firm decision, the same reasoning every other CFG-EDIT-* run gives', false),
  ('CFG-SET-GROUP-MEMBERS', 'manual',
   'which clients belong together is a judgment a person makes on purpose, never something a clock infers', false),
  ('RPT-BUILD-CONSOLIDATED-PACKAGE', 'manual',
   'combines two or more entities figures into one package, and a firm decides when that is ready to build -- nothing schedules a group the way it schedules a client', false)
on conflict (run_type) do nothing;

commit;
