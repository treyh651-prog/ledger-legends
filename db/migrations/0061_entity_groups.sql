-- 0061_entity_groups.sql
--
-- Group consolidation. A firm-defined set of client entities that get
-- combined into one report package with intercompany eliminations. Nothing
-- in this schema derives "the group" from tenancy.memberships -- a group is
-- firm-controlled setup data, the same reasoning that puts the chart of
-- accounts and client policies under the firm's own hand rather than under
-- whichever portal user happens to have access to which entities.
--
-- tenancy.has_group_access mirrors has_client_access/has_firm_access
-- (migration 0001): true only when the actor can see every active member of
-- the group, so a portal user can never see a combined figure that leaks a
-- sibling entity's numbers they could not otherwise see on their own.
--
-- report.consolidated_packages/consolidated_sections mirror
-- report.report_packages/report_sections (migration 0016) with client_id
-- replaced by group_id, plus member_count on the header so a reader knows
-- how many entities a figure represents without opening the notes section.
--
-- Forward only. No down migration.

begin;

-- ---------------------------------------------------------------------------
-- 1. tenancy.entity_groups / entity_group_members.
-- ---------------------------------------------------------------------------

-- id is char(26) ULID, not uuid, even though this table lives in the tenancy
-- schema alongside clients/firms/engagements (all uuid): those four predate
-- the run framework and are minted outside it (a client's id is generated by
-- the API route and passed into INTAKE-CREATE-CLIENT's own scope, never
-- derived). A group is run-created from the first row on, by
-- CFG-CREATE-ENTITY-GROUP, the same as every other reference-data row this
-- framework writes (categories, rules, mapping profiles) -- all char(26),
-- minted with derivedId() inside propose() so a create is reproducible
-- across preview and apply with no API-layer id-minting step of its own.
create table tenancy.entity_groups (
  id            char(26) primary key,
  firm_id       uuid not null references tenancy.firms(id),
  name          text not null,
  created_at    timestamptz not null default now(),
  archived_at   timestamptz
);

create table tenancy.entity_group_members (
  id            char(26) primary key,
  group_id      char(26) not null references tenancy.entity_groups(id),
  -- Denormalized from the parent group, same convention every tenant table
  -- in this schema follows (a leading firm_id index, a plain has_firm_access
  -- policy), rather than a per-row join back to entity_groups for RLS.
  firm_id       uuid not null references tenancy.firms(id),
  client_id     uuid not null references tenancy.clients(id),
  added_at      timestamptz not null default now(),
  -- Soft delete, not a hard delete: this codebase never truly deletes an
  -- audit-relevant row (categories deactivate, mapping profiles deactivate,
  -- clients archive). CFG-SET-GROUP-MEMBERS field-writes this instead of
  -- deleting the row, so a group's membership history stays legible.
  removed_at    timestamptz,
  constraint entity_group_member_unique unique (group_id, client_id)
);

create index on tenancy.entity_groups (firm_id) where archived_at is null;
create index on tenancy.entity_group_members (group_id) where removed_at is null;
create index on tenancy.entity_group_members (client_id) where removed_at is null;
create index on tenancy.entity_group_members (firm_id);

alter table tenancy.entity_groups enable row level security;
alter table tenancy.entity_groups force row level security;
alter table tenancy.entity_group_members enable row level security;
alter table tenancy.entity_group_members force row level security;

create policy firm_isolation on tenancy.entity_groups
  using ( (select tenancy.has_firm_access(firm_id)) )
  with check ( (select tenancy.has_firm_access(firm_id)) );

create policy firm_isolation on tenancy.entity_group_members
  using ( (select tenancy.has_firm_access(firm_id)) )
  with check ( (select tenancy.has_firm_access(firm_id)) );

-- A portal (client scoped) actor has no firm scope membership, so the
-- policies above give them nothing -- but a person whose own company is in
-- a group has to be able to read that group's name and roster to see "my
-- group" on their own portal screen. Read only: permissive select policies
-- are OR'd with firm_isolation's own select arm, and neither one touches
-- insert/update/delete, which stay firm staff only.
create policy member_can_read on tenancy.entity_groups
  for select
  using ( exists (
    select 1 from tenancy.entity_group_members m
    where m.group_id = id and m.removed_at is null and (select tenancy.has_client_access(m.client_id))
  ) );

create policy member_can_read on tenancy.entity_group_members
  for select
  using ( (select tenancy.has_client_access(client_id)) );

create trigger trg_freeze_firm_discriminator before update on tenancy.entity_groups
  for each row execute function tenancy.freeze_firm_discriminator();

-- entity_group_members is only ever field-written on removed_at (see
-- CFG-SET-GROUP-MEMBERS); which group, firm, and client a membership row
-- names must not move under that write.
create or replace function tenancy.freeze_group_member_discriminators()
returns trigger language plpgsql as $$
begin
  if new.firm_id is distinct from old.firm_id
     or new.group_id is distinct from old.group_id
     or new.client_id is distinct from old.client_id then
    raise exception 'tenant_discriminator_immutable on %', tg_table_name
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

create trigger trg_freeze_group_member_discriminators before update on tenancy.entity_group_members
  for each row execute function tenancy.freeze_group_member_discriminators();

-- Doc 04 Part 0's membership function, generalized to a group: true when the
-- actor can see the group's firm and has_client_access on every one of its
-- active members. "No member where has_client_access fails" rather than
-- "every member passes" so an empty-member group (nothing to leak) and a
-- group with at least one member outside the actor's reach both resolve
-- correctly without a separate empty-set branch.
create or replace function tenancy.has_group_access(p_group_id char(26))
returns boolean
language sql
stable
security definer
set search_path = tenancy, pg_catalog
as $$
  select exists (
    select 1 from tenancy.entity_groups g
    where g.id = p_group_id
      and (select tenancy.has_firm_access(g.firm_id))
      and not exists (
        select 1 from tenancy.entity_group_members m
        where m.group_id = g.id
          and m.removed_at is null
          and not (select tenancy.has_client_access(m.client_id))
      )
  );
$$;

revoke all on function tenancy.has_group_access(char(26)) from public;
grant execute on function tenancy.has_group_access(char(26)) to app_web, app_worker;

-- ---------------------------------------------------------------------------
-- 2. report.consolidated_packages / consolidated_sections.
-- ---------------------------------------------------------------------------

create table report.consolidated_packages (
  id             char(26) primary key,        -- ULID
  group_id       char(26) not null references tenancy.entity_groups(id),
  firm_id        uuid not null references tenancy.firms(id),
  version        integer not null default 1,

  period_start   date not null,
  period_end     date not null,
  basis          text not null default 'accrual',
  comparison_basis text not null default 'prior_period',
  comparison_available boolean not null default false,
  comparison_note text not null default '',
  state          text not null default 'draft',
  watermark      text,
  closed_with_exceptions boolean not null default false,
  exception_banner text,
  -- No single-entity equivalent needed: a consolidated header should say how
  -- many entities it combines without opening the notes section.
  member_count   integer not null default 0,
  section_count  integer not null default 0,
  omission_count integer not null default 0,
  content_checksum text not null,
  -- The combined fingerprint of every member's own ledger fingerprint,
  -- sorted by client_id so the same member set always hashes the same way
  -- regardless of query order. Plays the role report_packages.ledger_fingerprint
  -- plays for one entity: in the scope hash, so a posting on ANY member makes
  -- a rebuild a fresh scope rather than a stale dedupe hit.
  ledger_fingerprint text not null,

  vault_object_key text not null,
  vault_object_lock_mode text not null default 'GOVERNANCE',
  vault_retention_starts_on date not null,
  vault_object_lock_until date not null,

  built_by_run_id char(31),
  built_at       timestamptz not null,
  manual_override boolean not null default false,
  manual_override_by uuid,
  manual_override_at timestamptz,

  constraint consolidated_package_one_per_period unique (group_id, period_start, comparison_basis),
  constraint consolidated_package_window check (period_end >= period_start),
  constraint consolidated_package_state check (state in ('draft', 'superseded')),
  constraint consolidated_package_basis check (basis in ('accrual', 'cash')),
  constraint consolidated_package_comparison check (
    comparison_basis in ('prior_period', 'prior_year', 'budget', 'none')),
  constraint consolidated_package_lock_mode check (vault_object_lock_mode = 'GOVERNANCE'),
  constraint consolidated_package_retention_after_period check (
    vault_retention_starts_on >= period_end),
  constraint consolidated_package_lock_after_retention check (
    vault_object_lock_until > vault_retention_starts_on),
  constraint consolidated_package_counts check (
    member_count > 0 and section_count >= 0 and omission_count >= 0)
);

create index consolidated_packages_period on report.consolidated_packages (group_id, period_start);

create table report.consolidated_sections (
  id             char(26) primary key,
  group_id       char(26) not null references tenancy.entity_groups(id),
  firm_id        uuid not null references tenancy.firms(id),
  version        integer not null default 1,

  package_id     char(26) not null references report.consolidated_packages(id),
  sequence       integer not null,
  section_code   text not null,
  section_title  text not null,
  status         text not null,
  omission_reason text,
  as_of_date     date not null,
  banner_text    text,
  lines          jsonb not null default '[]'::jsonb,
  content_checksum text not null,

  created_by_run_id char(31),
  created_at     timestamptz not null default now(),
  manual_override boolean not null default false,
  manual_override_by uuid,
  manual_override_at timestamptz,

  constraint consolidated_section_one_per_package unique (package_id, section_code),
  constraint consolidated_section_status check (status in ('rendered', 'omitted')),
  constraint consolidated_section_sequence check (sequence > 0),
  constraint consolidated_section_reason_present check (
    (status = 'omitted' and omission_reason is not null)
    or (status = 'rendered' and omission_reason is null))
);

create index consolidated_sections_package on report.consolidated_sections (package_id, sequence);

alter table report.consolidated_packages enable row level security;
alter table report.consolidated_packages force row level security;
alter table report.consolidated_sections enable row level security;
alter table report.consolidated_sections force row level security;

create policy group_isolation on report.consolidated_packages
  using ( (select tenancy.has_group_access(group_id)) );
create policy group_isolation on report.consolidated_sections
  using ( (select tenancy.has_group_access(group_id)) );

-- Neither freeze_discriminators (firm_id/client_id) nor
-- freeze_firm_discriminator (firm_id only) covers a group_id column.
create or replace function tenancy.freeze_group_discriminators()
returns trigger language plpgsql as $$
begin
  if new.firm_id is distinct from old.firm_id
     or new.group_id is distinct from old.group_id then
    raise exception 'tenant_discriminator_immutable on %', tg_table_name
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

create trigger trg_freeze_group_discriminators before update on report.consolidated_packages
  for each row execute function tenancy.freeze_group_discriminators();
create trigger trg_freeze_group_discriminators before update on report.consolidated_sections
  for each row execute function tenancy.freeze_group_discriminators();

-- ---------------------------------------------------------------------------
-- 3. report.report_audit_events gains a nullable group_id, so the
-- consolidated run's one delivery row (report_available) reuses the single
-- existing delivery surface instead of forking a second audit table. Still
-- nobody is emailed; this is the same "one audit row, no address" shape
-- RPT-BUILD-PACKAGE already uses.
-- ---------------------------------------------------------------------------

alter table report.report_audit_events
  add column group_id char(26) references tenancy.entity_groups(id);

alter table report.report_audit_events
  alter column client_id drop not null;

alter table report.report_audit_events
  add constraint report_audit_event_one_subject check (
    (client_id is not null and group_id is null)
    or (client_id is null and group_id is not null)
  );

drop policy if exists client_isolation on report.report_audit_events;
create policy client_isolation on report.report_audit_events
  using (
    (client_id is not null and (select tenancy.has_client_access(client_id)))
    or (group_id is not null and (select tenancy.has_group_access(group_id)))
  )
  with check (
    (client_id is not null and (select tenancy.has_client_access(client_id)))
    or (group_id is not null and (select tenancy.has_group_access(group_id)))
  );

-- ---------------------------------------------------------------------------
